const pick = (a) => a[Math.floor(Math.random() * a.length)];

/** 새 랜덤 닉네임. avoid와 같은 이름은 피해요 (🎲 다시 굴렸는데 같은 이름이 나오지 않게) */
export function randomNick(avoid = '') {
  for (let t = 0; t < 10; t++) {
    const n = `${pick(ADJ)} ${pick(NOUN)}`;
    if (n !== avoid && Array.from(n).length <= 10) return n;
  }
  return `${pick(ADJ)} ${pick(NOUN)}`.slice(0, 10);
}
